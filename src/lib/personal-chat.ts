// Личные чаты на номере салона: как ассистент не отвечает маме владелицы.
//
// ОТКУДА ПРОБЛЕМА. При coexistence салон подключает свой обычный номер WhatsApp Business, а на нём
// переписываются не только клиенты: родные, подруги, поставщики. Каждый ответ ассистента в такой
// чат стоит денег (с 01.10.2026 Meta берёт за каждое сообщение) и ставит владелицу в неловкое
// положение.
//
// ДВА МЕХАНИЗМА.
//   1. Тег с телефона. Владелица пишет в чат «#личный» — номер навсегда уходит в «Контакты без
//      Админа». Она в этот момент уже в нужном чате, искать его в кабинете не нужно.
//   2. Молчание до признаков клиента. Пока чат не стал клиентским, ассистент отвечает только на
//      сообщение, похожее на клиентское: слово об услугах или записи, время, вежливое «вы»,
//      приветствие, фото. «Апа, кечинде келесиңби?» остаётся владелице.
//
// ПОЧЕМУ ПРАВИЛА, А НЕ ИИ. Решение принимается на каждом первом сообщении, до ответа. Правило
// бесплатно, мгновенно и объяснимо; нейросеть стоила бы денег и ошибалась бы непредсказуемо.
//
// КУДА ОШИБАТЬСЯ. Промолчать клиенту дороже, чем один раз ответить знакомому. Поэтому любой
// признак клиента побеждает, а само приветствие («Здравствуйте», «Салам») считается клиентским:
// так начинает большинство клиентов, а цена ошибки со знакомым — одно сообщение.

import { BUSINESS_STEMS, normalizeText } from "@/lib/excluded-suggestions";

/** «#личный», «#личное», «#Лично», «#жеке» — в любом месте сообщения. */
const PERSONAL_TAG = /(^|[^a-zа-яөүң0-9])#(личн[а-я]*|жеке)(?=$|[^a-zа-яөүң0-9])/i;

export function hasPersonalTag(text: string | null | undefined): boolean {
  if (!text) return false;
  return PERSONAL_TAG.test(normalizeText(text));
}

/** Клиентские слова, которых нет в BUSINESS_STEMS: опоздание, частые услуги. */
const CLIENT_STEMS = ["опозда", "кечик", "кечиг", "ногт", "тырмак", "волос"];

/** Время записи: «18:00», «9.30». */
const TIME_OF_DAY = /(^|[^0-9])([01]?[0-9]|2[0-3])[:.][0-5][0-9]($|[^0-9])/;

/** Вежливое обращение на «вы» / «сиз» — так пишут в салон, а не маме. */
const FORMAL_MARKERS = [
  /здравств/,
  /добр(ый|ое|ого)\s+(день|дня|утро|утра|вечер|вечера)/,
  /саламатсыз/,
  /(^|[^а-я])(вы|вас|вам|вами|ваш[а-я]*)(?=$|[^а-я])/,
  /(^|[^а-яөүң])сиз(де|ге|дер[а-яөүң]*)?(?=$|[^а-яөүң])/,
];

/** Сообщение из одного приветствия — после удаления всего, кроме букв. */
const GREETINGS = new Set([
  "здравствуйте",
  "здравствуй",
  "добрыйдень",
  "доброеутро",
  "добрыйвечер",
  "привет",
  "салам",
  "салем",
  "саламатсызбы",
  "ассаламуалейкум",
  "ассаламуалейкуум",
  "ассалямуалейкум",
  "hi",
  "hello",
]);

export function looksLikeClientMessage(input: {
  text: string | null | undefined;
  hasImage: boolean;
}): boolean {
  // Фото с незнакомого номера — почти всегда ногти, волосы или чек.
  if (input.hasImage) return true;
  const t = normalizeText(input.text ?? "").trim();
  if (!t) return false;
  if ([...BUSINESS_STEMS, ...CLIENT_STEMS].some((w) => t.includes(w))) return true;
  if (TIME_OF_DAY.test(t)) return true;
  if (FORMAL_MARKERS.some((re) => re.test(t))) return true;
  return GREETINGS.has(t.replace(/[^a-zа-яөүң]/g, ""));
}

/**
 * Чат уже клиентский: ассистент в нём отвечал, или хоть одно входящее не было отложено.
 *
 * Второе условие — ради клиентов, которые пишут пачкой: «Здравствуйте», «Хочу записаться»,
 * «Завтра». Ассистент ещё не ответил, но «Завтра» — продолжение клиентского разговора, а не
 * личное сообщение.
 */
export function isEngagedChat(
  rows: Array<{ direction?: string | null; kind?: string | null; meta?: any }>,
): boolean {
  return rows.some(
    (r) =>
      (r.direction === "out" && r.kind === "text") ||
      (r.direction === "in" && !r.meta?.personal_hold),
  );
}

/**
 * Рассылка, реклама, развод — то, что клиентом не бывает НИКОГДА.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ looksLikeClientMessage. Тот молчит только пока чат не стал клиентским: один
 * раз ответив, ассистент дальше отвечает на всё. Реклама же приходит и в клиентские чаты —
 * например, клиентка записалась полгода назад, а теперь её номер продали рассыльщикам. Каждый
 * такой ответ платный (Meta берёт за сообщение с 01.10.2026) и выглядит глупо.
 *
 * СПИСОК НАМЕРЕННО УЗКИЙ. Здесь можно ошибиться только в одну сторону: промолчать настоящему
 * клиенту дороже, чем один раз ответить рекламе. Поэтому сюда попадают лишь слова, которых в
 * разговоре о записи в салон не бывает в принципе. «Скидка», «акция», «промокод» СЮДА НЕ ВХОДЯТ:
 * про них спрашивают живые клиенты.
 */
const SPAM_STEMS = [
  "кредит",
  "займ",
  "микрозайм",
  // «рассрочка» сюда НЕ входит, хотя просилась: про оплату частями спрашивают живые клиенты, и
  // поймал это собственный тест. Ровно тот случай, ради которого список держится узким.
  "ставки на спорт",
  "букмекер",
  "казино",
  "инвестиц",
  "криптовалют",
  "биткоин",
  "форекс",
  "пассивный доход",
  "заработок в интернете",
  "вы выиграли",
  "вы стали победителем",
  "обнал",
  "продвижение вашего бизнеса",
  "накрутка подписчиков",
];

export function looksLikeSpam(text: string | null | undefined): boolean {
  if (!text) return false;
  const t = normalizeText(text);
  return SPAM_STEMS.some((w) => t.includes(w));
}

/**
 * Промолчать и оставить сообщение владелице?
 *
 * Два разных основания, и они не сводятся друг к другу:
 *   • чат ещё не клиентский и сообщение не похоже на клиентское — «апа, кечинде келесиңби?»;
 *   • рассылка или развод — в ЛЮБОМ чате, включая давно клиентский.
 */
export function shouldHoldForOwner(input: {
  chatAlreadyEngaged: boolean;
  text: string | null | undefined;
  hasImage: boolean;
}): boolean {
  if (looksLikeSpam(input.text)) return true;
  if (input.chatAlreadyEngaged) return false;
  return !looksLikeClientMessage(input);
}
