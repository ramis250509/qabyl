export function isIndustryKey(v: unknown): v is IndustryKey {
  return typeof v === "string" && v in INDUSTRIES_META;
}

export function normalizeIndustry(v: unknown): IndustryKey {
  return isIndustryKey(v) ? v : DEFAULT_INDUSTRY;
}
