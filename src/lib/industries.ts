// Инструкция по работе с фото и ценой — своя для каждой отрасли, под её реалии. Владелец
// получает готовый профессиональный текст сразу при выборе ниши (может отредактировать).
// `photoMode` определяет и заголовок поля, и смысл фотографии в этой сфере:
//   • "pricing"      — фото нужно для оценки стоимости (бьюти, барбершоп; детейлинг, ремонт…).
//   • "consultation" — фото нужно, чтобы разобрать ситуацию клиента и довести до записи, БЕЗ
//                      заочного диагноза и цены (косметология, стоматология, медицина).
//   • "none"         — фото для этой сферы не решает; поле только про то, как говорить о цене.
export type PhotoMode = "pricing" | "consultation" | "none";

export interface IndustryPricing {
  /** Роль фотографии в этой отрасли — задаёт и заголовок поля, и логику ассистента. */
  photoMode: PhotoMode;
  /** Заголовок поля в админке (меняется автоматически под photoMode). */
  label: string;
  /** Готовый профессиональный текст-подсказка, подставляемый по умолчанию. */
  default: string;
}

