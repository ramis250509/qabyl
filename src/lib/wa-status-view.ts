// Кто что видит в состоянии канала WhatsApp.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Состояние считается на сервере (computeWaStatus) и одно на всех: так
// сделано нарочно, иначе дашборд и вкладка «Каналы» через месяц расходятся в показаниях. Но
// «одно состояние» не означает «один адресат»: часть поломок принадлежит платформе, и владелице
// салона их показывать нечестно — она не может их починить.
//
// Здесь и только здесь живёт правило «что из этого показать конкретному человеку». Не в
// компоненте: компонентов четыре (дашборд, полоса каналов, вкладка «Каналы», карточка
// WhatsApp), и правило, размазанное по четырём, разъедется ровно так же, как разъезжалось само
// состояние.
//
// ЧТО ЭТО НЕ ДЕЛАЕТ. Не прячет факт поломки. Владелица по-прежнему видит, что канал не в строю
// — но тоном «идёт настройка», без красного и без кнопки, за которой для неё нет действия.

/** Минимум, который нужен правилу. Структурный тип: не тянет .server-модуль в браузерный бандл. */
type ViewableWaStatus = {
  connected: boolean;
  level: "ok" | "warn" | "error" | "idle";
  title: string;
  body: string;
  action?: unknown;
  audience?: "owner" | "platform";
};

/**
 * Состояние канала глазами конкретного человека.
 *
 * Супер-админ видит всё как есть: он тот, кто чинит. Остальным платформенная поломка
 * пересказывается как незаконченная настройка — это правда, и это не требует от них действий.
 *
 * Тон idle выбран не для мягкости: по контракту src/components/ui/status.tsx блока с тоном warn
 * или error не бывает без действия, а действия здесь нет и быть не может. idle означает «ещё не
 * настроено, но это не поломка» — ровно то, что происходит.
 */
export function waStatusForViewer<T extends ViewableWaStatus>(status: T, isSuperAdmin: boolean): T {
  if (isSuperAdmin) return status;
  if (status.audience !== "platform") return status;
  return {
    ...status,
    level: "idle",
    title: "WhatsApp подключён, заканчиваем настройку",
    body: "Осталось включить оплату сообщений — это делаем мы, на вашей стороне ничего не нужно. Пока настройка не закончена, ассистент не отвечает в WhatsApp: сообщения клиентов видны в «Переписках», ответить на них можно оттуда.",
    action: undefined,
  };
}

/**
 * Короткая подпись канала для плашки.
 *
 * Отдельная функция, а не тернарник в разметке, по той же причине, что и всё выше: подпись
 * рисуется в двух местах (дашборд и вкладка «Каналы»), и «подключён» против «работает» на двух
 * соседних экранах читается как два разных состояния.
 */
export function waChipText(status: Pick<ViewableWaStatus, "connected" | "level">): string {
  if (!status.connected) return "не подключён";
  // Подключён, но тон idle — единственный способ получить такое сочетание сейчас: платформенная
  // поломка, пересказанная владельцу выше. Называть её «требует внимания» значит звать человека
  // туда, где для него ничего нет.
  if (status.level === "idle") return "заканчиваем настройку";
  if (status.level === "ok") return "работает";
  return "требует внимания";
}
