// Одно решение: считать ли пропажу сессии настоящим выходом.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Всё остальное в auth-client.ts — браузер: localStorage, слушатели
// событий, supabase-клиент. Это правило — чистая функция от объекта ошибки, и от него зависит
// единственное необратимое действие во всём кабинете: отправить человека на экран входа. Такое
// правило должно проверяться тестами, а не пробоваться на живой владелице салона.
//
// ЦЕНА ОШИБКИ НЕСИММЕТРИЧНА, и правило написано исходя из этого:
//   • сочли временный сбой выходом — человек теряет работу и вводит пароль заново, а в половине
//     случаев ещё и решает, что приложение сломано;
//   • сочли настоящий выход временным сбоем — кабинет несколько секунд показывает загрузку и
//     после отказа сервера всё равно уводит на вход.
// Второе дешевле, поэтому по умолчанию ошибка считается временной.

/** Ровно то, что нужно правилу от ошибки supabase-js. */
export type TokenError = {
  name?: string;
  message?: string;
  status?: number;
  code?: string;
} | null;

/**
 * Сервер прямо сказал, что refresh-токен больше не действует?
 *
 * true — доступа действительно нет: токен отозвали, пользователя заблокировали, сессию закрыли
 * глобальным выходом на другом устройстве. Только в этом случае уместен экран входа.
 *
 * false — «не дозвонились»: нет сети, Supabase отвечает 5xx, телефон только что проснулся и
 * радиомодуль ещё не поднялся. supabase-js такие ошибки помечает именем AuthRetryableFetchError
 * и ставит им status 0 либо один из 502/503/504/520…530 (см. auth-js, lib/fetch.js).
 */
export function isTokenRejected(error: TokenError): boolean {
  if (!error) return false;
  if (error.name === "AuthRetryableFetchError") return false;
  const status = error.status;
  if (typeof status === "number") {
    if (status >= 500 || status === 0) return false;
    if (status >= 400) return true;
    // 2xx/3xx с ошибкой — состояние, которого быть не должно. Молчим и пробуем ещё раз.
    return false;
  }
  // Статуса нет: судим по коду GoTrue. Список закрытый — незнакомый код означает «не знаем»,
  // а «не знаем» здесь читается как «не выгонять».
  const code = String(error.code ?? "").toLowerCase();
  return (
    code.includes("refresh_token") ||
    code.includes("invalid_grant") ||
    code.includes("session_not_found") ||
    code.includes("user_banned") ||
    code.includes("session_expired")
  );
}
