// Правила управления доступами сотрудников, вынесенные из rbac.functions.ts, чтобы их можно было
// проверять тестами без сервера и базы.

export type RoleRow = { role: string; salon_id: string | null };

/**
 * Можно ли выдать человеку новый пароль из кабинета салона `salonId`.
 * Возвращает текст отказа или null, если можно.
 *
 * ПОЧЕМУ СМОТРИМ ВСЕ РОЛИ ЧЕЛОВЕКА, А НЕ ТОЛЬКО В ЭТОМ САЛОНЕ. Салон может завести кто угодно
 * (самостоятельная регистрация), а inviteEmployee привязывает к салону уже существующий аккаунт
 * по одной лишь почте. Если бы здесь проверялось только «есть роль в этом салоне», любой
 * зарегистрировавшийся выдал бы себе пароль от аккаунта владельца платформы или чужого салона.
 * Поэтому пароль меняем только тем, чей доступ целиком живёт внутри этого салона.
 */
export function passwordResetDenial(
  actorLevel: "owner" | "manager",
  salonId: string,
  targetRoles: RoleRow[],
): string | null {
  const here = targetRoles.filter((r) => r.salon_id === salonId);
  if (!here.length) return "У этого человека нет доступа к салону";

  const elsewhere = targetRoles.some((r) => r.role === "super_admin" || r.salon_id !== salonId);
  if (elsewhere) {
    return "У этого человека есть доступ к другому салону — пароль он меняет сам, через «Забыли пароль?» на экране входа";
  }

  // Администратор меняет пароль только мастерам — иначе он сменит пароль владельцу и войдёт
  // под ним.
  if (actorLevel === "manager" && !here.every((r) => r.role === "master")) {
    return "Администратор может менять пароль только мастерам";
  }
  return null;
}
