-- Ежечасная проверка здоровья подключений WhatsApp.
--
-- ЗАЧЕМ. Токен отзывают, WABA блокируют, шаблон отклоняют — и ни о чём из этого Meta не сообщает
-- нам сама (кроме шаблонов, и то только с этой недели, когда мы подписались на поле). До сих пор
-- единственным способом узнать было молчание ассистента, о котором сообщал салон: инцидент
-- 26.08.2026 у Lashes Nurzhan тянулся двое суток при нулевом трафике и пустых логах.
--
-- Задача превращает «клиенты не отвечают третий день» в «Qabyl написал вам, что доступ потерян»:
-- эндпоинт опрашивает Meta по каждому подключённому салону, обновляет состояние канала и кладёт
-- уведомление в колокольчик ТОЛЬКО на переходе в поломку — ежечасное напоминание об известной
-- проблеме обесценивает колокольчик быстрее, чем чинится проблема.
--
-- МИНУТА 7, А НЕ 0. В ноль уже стоят напоминания и другие задачи; одновременный старт даёт
-- всплеск запросов к Graph API ровно там, где мы бережём лимит приложения (200–5000 в час).
--
-- Идемпотентна: unschedule перед schedule, как в 20260817075649.

do $$
begin
  perform cron.unschedule('wa-health');
exception
  when others then null; -- задачи ещё нет — нормально при первом накате
end $$;

select cron.schedule(
  'wa-health',
  '7 * * * *',
  $$
  SELECT net.http_post(
    url := 'https://qabyl.com/api/internal/cron/wa-health',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', (SELECT public.internal_get_cron_secret())
    ),
    body := '{}'::jsonb,
    -- Салонов может быть много, и обход идёт последовательно, чтобы не бить по лимиту Meta
    -- всплеском. Тридцати секунд на это мало; берём с запасом.
    timeout_milliseconds := 120000
  ) AS request_id;
  $$
);

