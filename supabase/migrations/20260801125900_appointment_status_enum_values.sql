-- Значения статуса записи выносятся в отдельную миграцию.
--
-- Проблема, которую это лечит. `20260801130000_prepayment_schema.sql` добавлял
-- 'pending_payment' в тип appointment_status и тут же, в том же файле, строил по
-- нему частичный индекс:
--
--   CREATE INDEX ... ON appointments (hold_expires_at) WHERE status = 'pending_payment'
--
-- Postgres запрещает использовать только что добавленное значение перечисления в
-- той же транзакции, где оно появилось (SQLSTATE 55P04), а каждый файл миграции
-- выполняется одной транзакцией. Итог: цепочка миграций **невоспроизводима с
-- нуля**. На уже существующих базах всё работало, потому что значение к тому
-- моменту было добавлено раньше и другим путём.
--
-- Обнаружено 2026-08-15 при первом честном `supabase db reset` на локальной
-- базе. До этого никто ни разу не поднимал схему с чистого листа — на Токио мы
-- добавляли значения вручную, чтобы протолкнуть накат, и приняли это за разовую
-- неприятность. Это была не неприятность, а сломанное восстановление из
-- миграций.
--
-- Решение: значения добавляются здесь, в файле с меньшим номером, то есть в
-- ОТДЕЛЬНОЙ транзакции, которая коммитится до 20260801130000. Дальше блок
-- IF NOT EXISTS внутри 20260801130000 срабатывает вхолостую, а индекс строится
-- по уже существующему значению.
--
-- Сам 20260801130000 намеренно НЕ правится: он применён на всех живых базах, и
-- переписывать применённую миграцию — худшая из возможных привычек. Достаточно,
-- что теперь он получает готовое значение.
--
-- На существующих базах (прод, Токио) эта миграция — пустая операция: значения
-- давно на месте, обе проверки IF NOT EXISTS не срабатывают.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_enum e
    JOIN pg_type t ON t.oid = e.enumtypid
    WHERE t.typname = 'appointment_status' AND e.enumlabel = 'pending_payment'
  ) THEN
    ALTER TYPE public.appointment_status ADD VALUE 'pending_payment';
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_enum e
    JOIN pg_type t ON t.oid = e.enumtypid
    WHERE t.typname = 'appointment_status' AND e.enumlabel = 'payment_expired'
  ) THEN
    ALTER TYPE public.appointment_status ADD VALUE 'payment_expired';
  END IF;
END $$;
