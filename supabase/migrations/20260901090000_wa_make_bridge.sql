-- Мост через Make: временный транспорт WhatsApp на время ожидания App Review.
--
-- Пока приложение имеет только Standard Access, оно по правилам Meta не может обращаться к WABA
-- чужого бизнес-портфолио — вызов возвращает ошибку 200. Значит подключить салон к Cloud API
-- напрямую нельзя, и между нами и Meta временно встаёт Make со своим одобренным приложением.
--
-- Две колонки, обе необязательные. Салон считается «на мосту» тогда и только тогда, когда обе
-- заполнены: половина реквизитов — это молчащий ассистент, и лучше, чтобы такой салон выглядел
-- неподключённым, чем подключённым и немым.
--
-- Колонки namespace'ятся `wa_make_`, а не переиспользуют `whatsapp_cloud_*`: когда придёт
-- Advanced Access, мост выключается очисткой ровно этих двух полей, и облачные реквизиты рядом
-- при этом не страдают.

alter table public.salon_secrets
  add column if not exists wa_make_token text,
  add column if not exists wa_make_outbound_url text;

comment on column public.salon_secrets.wa_make_token is
  'Общий секрет моста Make. Make присылает его заголовком X-Qabyl-Token на входящих; мы отправляем его тем же заголовком на исходящих. Адрес вебхука Make секретом не является, поэтому аутентификация держится на этом значении.';

comment on column public.salon_secrets.wa_make_outbound_url is
  'Адрес custom webhook сценария Make, который отправляет сообщение в WhatsApp. Пусто — салон не на мосту.';
