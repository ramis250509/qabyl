-- Отдельный выключатель ассистента для WhatsApp.
--
-- ЗАЧЕМ. Выключателей было два, и оба были общими на весь салон: salons.ai_assistant_enabled и
-- salon_ai_assistant.enabled. Выключить ассистента в одном канале, оставив в другом, было нельзя
-- вообще — а это нужно постоянно: салон запускает Instagram на пробу, а WhatsApp хочет держать на
-- живом администраторе (или наоборот).
--
-- ПОЧЕМУ ТОЛЬКО ОДНА КОЛОНКА, А НЕ ДВЕ. У Instagram такой выключатель уже есть — это
-- salons.instagram_enabled: маршрут /api/public/ig проверяет его и для директа, и для ответов на
-- комментарии, то есть он ровно и означает «ИИ работает в Instagram». Заводить рядом с ним второй
-- instagram_ai_enabled значило бы сделать на одном экране две галочки, которые делают одно и то же,
-- — то самое, от чего мы этот кабинет и чистим.
--
-- DEFAULT TRUE — обязательно. Колонка появляется у салонов, которые прямо сейчас работают; любое
-- другое значение по умолчанию означает, что после применения миграции WhatsApp у всех замолчит.
alter table public.salons
  add column if not exists whatsapp_ai_enabled boolean not null default true;

comment on column public.salons.whatsapp_ai_enabled is
  'Отвечает ли ИИ-ассистент на входящие в WhatsApp. Общий выключатель салона (ai_assistant_enabled) имеет приоритет: выключен он — молчат все каналы. Аналог для Instagram — instagram_enabled.';
