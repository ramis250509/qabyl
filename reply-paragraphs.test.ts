// Ответ ассистента не должен приходить «простынёй».
//
// Запуск: bun test reply-paragraphs

import { describe, expect, test } from "bun:test";
import { splitIntoParagraphs } from "./src/lib/wa-agent-v4.server";

describe("простыня разбивается на абзацы", () => {
  test("три мысли подряд — три абзаца", () => {
    const flat =
      "Отлично! Я передаю Ваш запрос на запись на курс нашему администратору. Он свяжется с Вами в ближайшее время, чтобы обсудить все детали и оформить запись.";
    expect(splitIntoParagraphs(flat)).toBe(
      "Отлично!\n\n" +
        "Я передаю Ваш запрос на запись на курс нашему администратору.\n\n" +
        "Он свяжется с Вами в ближайшее время, чтобы обсудить все детали и оформить запись.",
    );
  });
});

describe("что трогать нельзя", () => {
  test("два предложения остаются вместе", () => {
    // Два предложения через абзац — это уже рубленая речь, а не забота о читателе.
    const short = "Женская стрижка стоит 1200 сом. Записать вас на завтра?";
    expect(splitIntoParagraphs(short)).toBe(short);
  });

  test("совсем короткий ответ не дробим, даже если мыслей три", () => {
    const tiny = "Да. Хорошо. Жду вас.";
    expect(splitIntoParagraphs(tiny)).toBe(tiny);
  });

  test("сводка подтверждения не переформатируется", () => {
    // Здесь переносы расставлены шаблоном осознанно: тронуть их — сломать сводку.
    const summary =
      "Пожалуйста, подтвердите запись:\n\n✂️ Услуга: Женская стрижка\n👤 Мастер: Айгуль\n🕒 Время: 18:30\n\nВсё верно?";
    expect(splitIntoParagraphs(summary)).toBe(summary);
  });

  test("адрес салона не разваливается по «г.»", () => {
    // Мина: «г.» — это конец слова, а не конец предложения, и следом идёт заглавная. Адрес
    // встречается в каждом втором ответе, поэтому проверка здесь постоянная.
    const withAddress =
      "Мы находимся по адресу Ахунбаева 189, г. Бишкек, рядом с остановкой. Работаем с 9 до 21, без выходных. Ждём вас в гости!";
    const out = splitIntoParagraphs(withAddress);
    expect(out).not.toContain("г.\n\n");
    expect(out.split("\n\n")).toHaveLength(3);
  });

  test("много предложений не режем — вышла бы рубленая речь", () => {
    const many =
      "Здравствуйте! Кератин держится три месяца. Ботокс восстанавливает. Окрашивание делаем в один тон. Стрижка занимает час. Ждём вас!";
    expect(splitIntoParagraphs(many)).toBe(many);
  });

  test("пустая строка и пробелы не ломают", () => {
    expect(splitIntoParagraphs("")).toBe("");
    expect(splitIntoParagraphs("   ")).toBe("   ");
  });
});
